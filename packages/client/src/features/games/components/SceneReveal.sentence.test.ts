import { describe, expect, it } from 'vitest';
import { sentenceWith } from './SceneReveal';

/**
 * 🔴 리빌 자막은 **그 낱말이 있는 문장 하나**만 보여준다. 쪽 전체를 얹으면 삽화 위에 세 문장이
 *    깔려 아무도 안 읽는다(2026-08-18 사용자 지적).
 */
const PAGE =
  '밤이면 할머니는 다듬이돌에 웃김을 올려놓고 또닥또닥 방망이질을 했어요. ' +
  '그러면서도 이야기 타령이었지요. "이야기, 이야기! 짧은 거라도 좋구려." ' +
  '할아버지는 반짇고리 옆에 앉아 머리만 벅벅 긁었어요.';

describe('리빌 자막 — 낱말이 있는 문장만', () => {
  it('세 문장 중 그 낱말이 든 문장만 남긴다', () => {
    expect(sentenceWith(PAGE, '머리')).toBe('할아버지는 반짇고리 옆에 앉아 머리만 벅벅 긁었어요.');
  });

  it('대사는 닫는 따옴표까지 한 문장으로 본다', () => {
    expect(sentenceWith(PAGE, '이야기')).toBe('그러면서도 이야기 타령이었지요.');
  });

  // 🔴 못 찾으면 자르지 않는다 — 색인이 물결(고~기)·조사 때문에 놓치는 낱말이 있고,
  //    그때 빈 자막을 내놓는 것보다 원문을 그대로 두는 게 낫다.
  it('낱말이 본문에 없으면 원문 그대로', () => {
    expect(sentenceWith(PAGE, '없는낱말')).toBe(PAGE);
  });

  it('강조어가 없으면 원문 그대로', () => {
    expect(sentenceWith(PAGE)).toBe(PAGE);
  });
});
