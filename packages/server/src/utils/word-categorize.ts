/** 단어 → 매칭되는 카테고리 배열 (substring 매칭, 다중 매칭 가능) */
export function categorizeWord(entry: VocabEntry): WordCategoryId[] {
  const haystack = `${entry.word} ${entry.korean ?? ''}`.toLowerCase();
  const out: WordCategoryId[] = [];
  for (const [cat, keywords] of Object.entries(RULES) as [WordCategoryId, string[]][]) {
    if (keywords.some((kw) => haystack.includes(kw.toLowerCase()))) {
      out.push(cat);
    }
  }
  return out;
}

/** vocabulary-db 전체에서 두 카테고리에 해당하는 단어 풀 반환 */
export function poolByCategories(
  entries: VocabEntry[],
  cat1: WordCategoryId,
  cat2: WordCategoryId
): { cat1Words: VocabEntry[]; cat2Words: VocabEntry[] } {
  const cat1Words: VocabEntry[] = [];
  const cat2Words: VocabEntry[] = [];
  for (const e of entries) {
    const cats = categorizeWord(e);
    if (cats.includes(cat1) && !cats.includes(cat2)) cat1Words.push(e);
    else if (cats.includes(cat2) && !cats.includes(cat1)) cat2Words.push(e);
  }
  return { cat1Words, cat2Words };
}
