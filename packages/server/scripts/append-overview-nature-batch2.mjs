const dump = JSON.parse(
  fs.readFileSync(path.join(__dirname, '_data', 'books-missing-overview.json'), 'utf-8')
);
const stillMissing = dump.filter((x) => !map[x.id]);

const PHONICS_TITLE_RE = /^[0-9]+\.\s/;
const remaining = stillMissing.filter((x) => {
  const c = x.category || '';
  if (c === '영어 파닉스' || c === '한글 파닉스') return false;
  if (PHONICS_TITLE_RE.test(x.title)) return false;
  // 명작은 batch1 에서 처리됐으므로 still missing 에 남은 것은 자연 관찰 + 동물책
  return true;
});

const norm = (t) => t.replace(/-복사본\([0-9]+\)$/, '').trim();

const added = {};
const unmatched = [];
for (const x of remaining) {
  const key = norm(x.title);
  const ov = TITLE_TO_OVERVIEW[key];
  if (ov) added[x.id] = ov;
  else unmatched.push({ id: x.id, title: x.title, key });
}

console.log(`총 자연 관찰 batch entries: ${remaining.length}`);
console.log(`매칭됨: ${Object.keys(added).length}`);
console.log(`매칭 안 됨: ${unmatched.length}`);
if (unmatched.length) {
  console.log('--- unmatched (key) ---');
  for (const u of unmatched) console.log(`  ${u.title} → key="${u.key}"`);
}

if (process.argv.includes('--apply')) {
  const next = { ...map, ...added };
  fs.writeFileSync(mapPath, JSON.stringify(next, null, 2), 'utf-8');
  console.log(`\n✅ overview-map.json 갱신 — 총 ${Object.keys(next).length} entries`);
} else {
  console.log('\n[DRY-RUN] --apply 추가 시 overview-map.json 에 append');
}
