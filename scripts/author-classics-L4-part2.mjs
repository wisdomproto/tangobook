function buildStorybook(book, level, texts) {
  const id = `${book.bid}__${level}`;
  const edu = EDU[book.bid] ?? { moral: '', vocabulary: [] };
  return {
    id,
    title: `${book.title} (${level})`,
    type: 'storybook',
    readingLevel: level,
    targetAge: '7-8',
    artStyle: 'watercolor',
    category: '세계 명작',
    folder: `세계 명작 (${level})`,
    isPublic: false,
    createdAt: new Date().toISOString(),
    characters: [],
    coverPrompt: '',
    coverAspectRatio: '16:9',
    pages: texts.map((text, i) => ({
      pageNumber: i + 1,
      text,
      scene_description: '',
      scene_description_en: '',
      scene_structure: { characters: '', background: '', atmosphere: '', characters_en: '', background_en: '', atmosphere_en: '' },
    })),
    key_objects: [],
    educational_content: { vocabulary: edu.vocabulary, quiz: [], learning_objectives: [], moral_lesson: edu.moral },
    coverImages: [], keyObjectImages: [], games: [], blogPosts: [], cardNewsProjects: [], audiobookProjects: [],
    referenceContent: `레벨: ${level} (6-7세) · ${texts.length}페이지 · 원전 "${book.original}" 기반 직접 저술`,
  };
}

async function apiJson(path, init) {
  const res = await fetch(`${API}${path}`, init);
  const text = await res.text();
  let json;
  try { json = JSON.parse(text); } catch { throw new Error(`${res.status} ${path}: ${text.slice(0, 300)}`); }
  if (!res.ok || json.success === false) throw new Error(`${res.status} ${path}: ${json?.error ?? text.slice(0, 300)}`);
  return json.data;
}

async function main() {
  console.log(`━━ 세계명작 L4 (6-7세) Part 2: ${BOOKS.length}권 직접 저술 ━━\n`);
  const results = [];
  for (const book of BOOKS) {
    const texts = PAGES[book.bid];
    if (!texts || texts.length !== 22) {
      console.error(`✗ ${book.title} L4: PAGES 누락 또는 페이지수 불일치 (${texts?.length ?? 0})`);
      results.push({ title: book.title, ok: false });
      continue;
    }
    try {
      const sb = buildStorybook(book, 'L4', texts);
      const saved = await apiJson('/storybooks', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ storybook: sb }),
      });
      const chars = texts.reduce((s, t) => s + t.replace(/\s/g, '').length, 0);
      console.log(`✓ ${book.title} L4: 22p · ${chars}자 · ${saved.id}`);
      results.push({ title: book.title, chars, ok: true });
    } catch (err) {
      console.error(`✗ ${book.title} L4: ${err.message}`);
      results.push({ title: book.title, ok: false, error: err.message });
    }
  }
  const ok = results.filter(r => r.ok);
  console.log(`\n성공 ${ok.length}/${results.length}`);
  process.exit(results.some(r => !r.ok) ? 1 : 0);
}

