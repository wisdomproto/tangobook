function buildStorybook(book, level, texts) {
  const b = bid(book.no);
  const id = level === book.launch ? b : `${b}__${level}`;
  const folder = level === book.launch ? '세계 명작' : `세계 명작 (${level})`;
  const edu = EDU[book.no] ?? { moral: '', vocabulary: [] };
  return {
    id,
    title: `${book.t}${level === book.launch ? '' : ' (' + level + ')'}`,
    type: 'storybook',
    readingLevel: level,
    targetAge: TARGET_AGE[level],
    artStyle: 'watercolor',
    category: '세계 명작',
    folder,
    isPublic: false,
    createdAt: new Date().toISOString(),
    characters: [],
    coverPrompt: '',
    coverAspectRatio: '16:9',
    pages: texts.map((text, i) => ({
      pageNumber: i + 1,
      text,
      scene_description: '',
      scene_description_en: '',
      scene_structure: { characters: '', background: '', atmosphere: '', characters_en: '', background_en: '', atmosphere_en: '' },
    })),
    key_objects: [],
    educational_content: { vocabulary: edu.vocabulary, quiz: [], learning_objectives: [], moral_lesson: edu.moral },
    coverImages: [], keyObjectImages: [], games: [], blogPosts: [], cardNewsProjects: [], audiobookProjects: [],
    referenceContent: `레벨: ${level} (${AGE_LABEL[level]}) · ${texts.length}페이지 · 원전 "${book.o}" 기반 직접 저술`,
  };
}

async function apiJson(path, init) {
  const res = await fetch(`${API}${path}`, init);
  const text = await res.text();
  let json;
  try { json = JSON.parse(text); } catch { throw new Error(`${res.status} ${path}: ${text.slice(0, 300)}`); }
  if (!res.ok || json.success === false) throw new Error(`${res.status} ${path}: ${json?.error ?? text.slice(0, 300)}`);
  return json.data;
}

async function main() {
  console.log('━━ 세계명작 신규 Part 1 (31~36) ━━\n');
  const results = [];
  for (const book of BOOKS) {
    for (const lv of book.levels) {
      const texts = PAGES[book.no]?.[lv];
      if (!texts) {
        console.error(`✗ ${book.t} ${lv}: PAGES 누락`);
        results.push({ title: book.t, lv, ok: false });
        continue;
      }
      try {
        const sb = buildStorybook(book, lv, texts);
        const saved = await apiJson('/storybooks', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ storybook: sb }),
        });
        const chars = texts.reduce((s, t) => s + t.replace(/\s/g, '').length, 0);
        console.log(`✓ ${book.t} ${lv}: ${texts.length}p · ${chars}자 · ${saved.id}`);
        results.push({ title: book.t, lv, chars, ok: true });
      } catch (err) {
        console.error(`✗ ${book.t} ${lv}: ${err.message}`);
        results.push({ title: book.t, lv, ok: false });
      }
    }
  }
  const ok = results.filter(r => r.ok);
  console.log(`\n성공 ${ok.length}/${results.length}`);
  process.exit(results.some(r => !r.ok) ? 1 : 0);
}

main().catch(e => { console.error(e); process.exit(1); });
