async function apiJson(path, init) {
  const res = await fetch(`${API}${path}`, init);
  const text = await res.text();
  let json;
  try { json = JSON.parse(text); } catch { throw new Error(`${res.status} ${path}: ${text.slice(0, 300)}`); }
  if (!res.ok || json.success === false) throw new Error(`${res.status} ${path}: ${json?.error ?? text.slice(0, 300)}`);
  return json.data;
}

async function main() {
  console.log(`━━ 부모 가이드 병합 (${Object.keys(GUIDES).length}권) ━━\n`);
  let ok = 0, fail = 0;
  for (const [bid, guide] of Object.entries(GUIDES)) {
    try {
      const sb = await apiJson(`/storybooks/${bid}`);
      const merged = { ...sb, parentGuide: guide };
      await apiJson('/storybooks', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ storybook: merged }),
      });
      console.log(`✓ ${bid} ${sb.title}`);
      ok++;
    } catch (err) {
      console.error(`✗ ${bid}: ${err.message}`);
      fail++;
    }
  }
  console.log(`\n성공 ${ok}권, 실패 ${fail}권`);
  process.exit(fail > 0 ? 1 : 0);
}

main().catch(e => { console.error(e); process.exit(1); });
