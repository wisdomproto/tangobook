async function apiJson(path, init) {
  const res = await fetch(`${API}${path}`, init);
  const text = await res.text();
  let json;
  try { json = JSON.parse(text); } catch { throw new Error(`${res.status} ${path}: ${text.slice(0, 300)}`); }
  if (!res.ok || json.success === false) throw new Error(`${res.status} ${path}: ${json?.error ?? text.slice(0, 300)}`);
  return json.data;
}

async function main() {
  console.log('━━ 세계명작 신규 Part 2 (37~42) ━━\n');
  const results = [];
  for (const book of BOOKS) {
    for (const lv of book.levels) {
      const texts = PAGES[book.no]?.[lv];
      if (!texts) { console.error(`✗ ${book.t} ${lv}: PAGES 누락`); results.push({ ok: false }); continue; }
      try {
        const sb = buildStorybook(book, lv, texts);
        const saved = await apiJson('/storybooks', {
          method: 'POST', headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ storybook: sb }),
        });
        const chars = texts.reduce((s, t) => s + t.replace(/\s/g, '').length, 0);
        console.log(`✓ ${book.t} ${lv}: ${texts.length}p · ${chars}자 · ${saved.id}`);
        results.push({ ok: true });
      } catch (err) { console.error(`✗ ${book.t} ${lv}: ${err.message}`); results.push({ ok: false }); }
    }
  }
  const ok = results.filter(r => r.ok);
  console.log(`\n성공 ${ok.length}/${results.length}`);
  process.exit(results.some(r => !r.ok) ? 1 : 0);
}

main().catch(e => { console.error(e); process.exit(1); });
